    private void btnCreateUserActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateUserActionPerformed
        String fullName = txtFullName.getText().trim();
        String email = txtEmail.getText().trim();
        String phoneNumber = txtPhoneNumber.getText().trim();
        String password = new String(txtPassword.getPassword());
        String role = cbRole.getSelectedItem().toString();
        boolean active = cbActive.isSelected();

        if (fullName.isEmpty() || email.isEmpty() || phoneNumber.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(CreateUserDialog, "Please fill in all fields.");
            return;
        }

        User user = null;

//        CREATE
        if (editingUserId == null) {
            switch (role) {
                case "ADMIN":
                    user = new AdminStaff(
                            fullName,
                            email,
                            phoneNumber,
                            password,
                            active
                    );
                    break;

                case "MEDICAL_MANAGER":
                    user = new MedicalManager(
                            fullName,
                            email,
                            phoneNumber,
                            password,
                            active
                    );
                    break;

                case "DOCTOR":
                    user = new Doctor(
                            fullName,
                            email,
                            phoneNumber,
                            password,
                            active
                    );
                    break;

                case "PATIENT":
                    user = new Patient(
                            fullName,
                            email,
                            phoneNumber,
                            password,
                            active
                    );
                    break;
            }

            if (user != null) {
                boolean success = adminStaff.createUser(user);
                if (success) {
                    JOptionPane.showMessageDialog(CreateUserDialog, "User created successfully.");
                    CreateUserDialog.dispose();

                    loadUsers();
                } else {
                    JOptionPane.showMessageDialog(CreateUserDialog, "Failed to create user.");
                }
            }
        } else {
//            EDIT
            switch (role) {
                case "ADMIN":
                    user = new AdminStaff(
                            editingUserId,
                            fullName,
                            email,
                            phoneNumber,
                            password,
                            active
                    );
                    break;

                case "MEDICAL_MANAGER":
                    user = new MedicalManager(
                            editingUserId,
                            fullName,
                            email,
                            phoneNumber,
                            password,
                            active
                    );
                    break;

                case "DOCTOR":
                    user = new Doctor(
                            editingUserId,
                            fullName,
                            email,
                            phoneNumber,
                            password,
                            active
                    );
                    break;

                case "PATIENT":
                    user = new Patient(
                            editingUserId,
                            fullName,
                            email,
                            phoneNumber,
                            password,
                            active
                    );
                    break;
            }

            if (user != null) {
                boolean success = adminStaff.updateUser(user);

                if (success) {
                    JOptionPane.showMessageDialog(CreateUserDialog, "User updated successfully.");

                    CreateUserDialog.dispose();

                    editingUserId = null;

                    loadUsers();
                } else {
                    JOptionPane.showMessageDialog(CreateUserDialog, "Failed to update user.");
                }
            }
        }
    }//GEN-LAST:event_btnCreateUserActionPerformed

