    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        Authentication auth = new Authentication(
            tempname.getText(),
            temppass.getText()
        );

        try {
            String role = auth.login();
            System.out.println(role);

            switch (role) {
                case "ADMIN":{
                    User loggedInUser = auth.getLoggedInUser();

                    if (loggedInUser instanceof AdminStaff) {
                        AdminStaff admin = (AdminStaff) loggedInUser;
                        AdminPage adminPage = new AdminPage(admin);
                        adminPage.setVisible(true);

                        // Close login page
                        dispose();
                    }

                    break;
                }
                case "MEDICAL_MANAGER":{
                    User loggedInUser = auth.getLoggedInUser();
                    if (loggedInUser instanceof MedicalManager) {
                        MedicalManager MM = (MedicalManager) loggedInUser;
                        MedicalManagerPage MMpage = new MedicalManagerPage(MM);
                        MMpage.setVisible(true);
                        dispose();

                    }
                    break;
                }
                case "DOCTOR":{

                    User loggedInUser = auth.getLoggedInUser();

                    if (loggedInUser instanceof Doctor) {
                        Doctor doctor = (Doctor) loggedInUser;
                        menudoctore doctorpage = new menudoctore(doctor);
                        doctorpage.setVisible(true);

                        // Close login page
                        dispose();
                    }
                    break;
                }
                case "PATIENT":{
                    User loggedInUser = auth.getLoggedInUser();

                    if (loggedInUser instanceof Patient) {
                        Patient patient = (Patient) loggedInUser;
                        PatientMenuPage PatientPage = new PatientMenuPage(patient);
                        PatientPage.setVisible(true);

                        // Close login page
                        dispose();
                        break;
                    }}

                    default:
                    lblErrorMessage.setText("Invalid email or password");
                    break;
                }

            } catch (IOException ex) {
                lblErrorMessage.setText("Error reading account file");
                System.getLogger(LoginPage.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            }
    }//GEN-LAST:event_jButton1ActionPerformed

