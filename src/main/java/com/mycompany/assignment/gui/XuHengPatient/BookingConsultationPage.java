    public BookingConsultationPage(Patient patient) throws IOException {
        initComponents();
        this.patient = patient;
        model.setColumnIdentifiers(columnName);
        List<doctorShift> slots = patient.viewAvailableSlots();
        for (doctorShift slot : slots) {
        model.addRow(new Object[]{
            slot.getShiftDate(),
            slot.getStartTime(),
            slot.getEndTime(),
            slot.getDoctor().getUserId(),
            slot.getDoctor().getFullName()
        });
        }
        
        for (int row = 0; row < jTable1.getRowCount(); row++) {
            String doctorID = jTable1.getValueAt(row, 3).toString();

            boolean exists = false;

            for (int i = 0; i < comboModel.getSize(); i++) {
                if (comboModel.getElementAt(i).equals(doctorID)) {
                    exists = true;
                    break;
                }
            }

            if (!exists) {
                comboModel.addElement(doctorID);
            }
        }

        DoctorIDCMB.setModel(comboModel);
        
}

