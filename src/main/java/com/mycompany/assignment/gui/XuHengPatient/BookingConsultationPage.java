    private void BookingActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BookingActionPerformed
        LocalDate AD =null;
        LocalTime ST = null;
        LocalTime ET = null;
        try{
            AD = LocalDate.parse(AppDateTF.getText());
        }catch(DateTimeParseException ex){
            JOptionPane.showMessageDialog(null, "Please follow LocalDate Format YYYY-MM-DD, eg. 2026-01-31");
            return;
        }
        try{
            ST = LocalTime.parse(STTF.getText());
            ET = LocalTime.parse(ETTF.getText());
        }catch(DateTimeParseException ex){
            JOptionPane.showMessageDialog(null, "Please follow LocalTime Format HH:MM(24 hours format), eg. 09:30");
            return;
        }
        
        try {
            Appointment APT = new Appointment(
                    patient.getUserId(),
                    DoctorIDCMB.getSelectedItem().toString(),
                    AD,
                    ST,
                    ET);
            
            patient.bookAppointment(APT);
            JOptionPane.showMessageDialog(null, "Appointment Booked.");
            AppDateTF.setText("");
            STTF.setText("");
            ETTF.setText("");
        } catch (IOException ex) {
            System.getLogger(BookingConsultationPage.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
            JOptionPane.showMessageDialog(null, "System error. Please try again.");
        }catch(IllegalArgumentException ex){
            JOptionPane.showMessageDialog(null, ex.getMessage());
        }
        catch(Exception ex){
            JOptionPane.showMessageDialog(null, "System error. Please try again.");
        }
    }//GEN-LAST:event_BookingActionPerformed

