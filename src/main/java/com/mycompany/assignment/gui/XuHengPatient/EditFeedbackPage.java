    private void SubmitBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SubmitBTNActionPerformed
        int row = jTable1.getSelectedRow();
        if (CommentTA.getText().trim().isEmpty()){
            JOptionPane.showMessageDialog(null, "Please provide comment.");
        }else if(row == -1){
            JOptionPane.showMessageDialog(null, "Please select a feedback to change.");
        }
        else{
        String FeedbackID = String.valueOf(model.getValueAt(row, 0));
        patient.editFeedback(FeedbackID, CommentTA.getText());
        JOptionPane.showMessageDialog(null, "Comment Edited.");
        try {
            EditFeedbackPage page = new EditFeedbackPage(patient);
            page.setVisible(true);
            dispose();
        } catch (IOException ex) {
            JOptionPane.showMessageDialog(null, "System error. Please try again.");
            System.getLogger(EditFeedbackPage.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }}
        
    }//GEN-LAST:event_SubmitBTNActionPerformed

