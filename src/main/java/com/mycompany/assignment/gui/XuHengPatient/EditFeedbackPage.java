    public EditFeedbackPage(Patient patient) throws FileNotFoundException, IOException {
        initComponents();
        this.patient = patient;
        model.setColumnIdentifiers(columnName);
        FileReader fr = new FileReader("Feedback.txt");
        BufferedReader br = new BufferedReader(fr);
        ArrayList<String[]> Feedbacks =new ArrayList<>();
        String line;
        while ((line=br.readLine())!=null){
            Feedbacks.add(line.split(";"));
        }
        int i = 0;
        while(i<Feedbacks.size()){
            if((Feedbacks.get(i)[1]).equals(patient.getUserId())){
                
                String line2;
                String doctorName = null;
                FileReader fr2 = new FileReader("accountlist.txt");
                BufferedReader br2 = new BufferedReader(fr2);
                while ((line2 = br2.readLine()) != null) {
                        String value2[] = line2.split(",");
                        if(value2[0].equals(Feedbacks.get(i)[2])){
                            doctorName = value2[1];
                            break;
                        }
                    } 
                    br2.close();
                    fr2.close();
                        
                Object[] row ={
                    Feedbacks.get(i)[0],
                    Feedbacks.get(i)[2],
                    doctorName,
                    Feedbacks.get(i)[3],
                    Feedbacks.get(i)[4],
                    Feedbacks.get(i)[5]
                };
                model.addRow(row);
                i++;
            }else{
                i++;
            }
        }
        br.close();
        fr.close();
    }

