    public FeedbackPage(Patient patient) throws FileNotFoundException, IOException {
        initComponents();
        this.patient = patient;
        model.setColumnIdentifiers(columnName);
        try(FileReader fr = new FileReader("AppointmentSchedule.txt");
            BufferedReader br = new BufferedReader(fr);){
           
            String line;
            
            while ((line = br.readLine()) != null) {
                String value[] = line.split(",");
                String doctorID = value[2];
                String doctorName = null;
                
                if(value[1].equals(patient.getUserId()) && value[6].equals("COMPLETE")){
                    String line2;
                    doctorID = value[2];
                    
                     
                    FileReader fr1 = new FileReader("accountlist.txt");
                    BufferedReader br1 = new BufferedReader(fr1);
                    
                    while ((line2 = br1.readLine()) != null) {
                        String value2[] = line2.split(",");
                        if(value2[0].equals(doctorID)){
                            doctorName = value2[1];
                            break;
                        }
                    } 
                    br1.close();
                    fr1.close();
                }
                
                boolean exists = false;
                
                for (int row = 0; row < model.getRowCount(); row++) { //getRowCount to know how many row at current
                    if (model.getValueAt(row, 0).toString().equals(doctorID)) {
                        exists = true;
                        break;
                    }
                }
                
                if (!exists && doctorName !=null) {
                    model.addRow(new Object[]{
                        doctorID,
                        doctorName
                    });
                }
            }   
        }
        catch(Exception e){
            JOptionPane.showMessageDialog(null, "System Error. Please try again.");
            JOptionPane.showMessageDialog(null, e);
        }
        
        
    }

