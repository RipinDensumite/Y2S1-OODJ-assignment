    private void SubmitBTNActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_SubmitBTNActionPerformed
        int row = jTable1.getSelectedRow();
        if (row == -1){
            JOptionPane.showMessageDialog(null, "Please select a doctor.");
        }
        else if(Rating == 0 || CommentTA.getText().isEmpty()){
            JOptionPane.showMessageDialog(null, "Please provide rating and service.");
        }else{
            try {
                patient.submitFeedback(Rating, CommentTA.getText(),String.valueOf(model.getValueAt(row, 0)));
            } catch (IOException ex) {
                System.getLogger("Feedback Submit Failed.");
            }
            JOptionPane.showMessageDialog(null, "Feedback Submitted.");
            CommentTA.setText("");
            buttonGroup1.clearSelection();
        }
    }//GEN-LAST:event_SubmitBTNActionPerformed

