    private void loadIncompleteConsultations() {
    try {
        BufferedReader br = new BufferedReader(new FileReader("Consultation.txt"));

        String line;
        StringBuilder record = new StringBuilder();
        StringBuilder display = new StringBuilder();

        while ((line = br.readLine()) != null) {

            if (line.trim().isEmpty()) {
                continue;
            }

            record.append(line).append("\n");

            if (line.startsWith("Completed:")) {

                if (line.equals("Completed: false")) {
                    display.append(record).append("\n");
                }

                record.setLength(0);
            }
        }

        br.close();

        jTextArea1.setText(display.toString());
        jTextArea1.setEditable(false);

    } catch (IOException e) {
        JOptionPane.showMessageDialog(this, "Error reading Consultation.txt");
    }
}

