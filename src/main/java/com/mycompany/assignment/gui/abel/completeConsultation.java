    private void completedbtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_completedbtnActionPerformed
        // TODO add your handling code here:
        String consultationId=consultationidtxt.getText().trim();
        
        if(!yesRB.isSelected()){
            JOptionPane.showMessageDialog(this,"Radio button not pressed");
            return;
        }
        
        
        Consultation consultation = new Consultation(
                consultationId,
                null,
                ""
        );
        try {
            consultation.completeConsultation();
        } catch (IOException ex) {
            System.getLogger(completeConsultation.class.getName()).log(System.Logger.Level.ERROR, (String) null, ex);
        }
        JOptionPane.showMessageDialog(this,"Consultation completed");
        new menudoctore(doctor).setVisible(true);
        this.dispose();
    }//GEN-LAST:event_completedbtnActionPerformed

